import pandas as pd
import torch
import numpy as np
from tqdm import tqdm
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score
from unsloth import FastVisionModel
from transformers import set_seed 

print("loading...")
model, processor = FastVisionModel.from_pretrained(
    "gemma_4_meme",
    load_in_4bit = True,
    device_map = "balanced",
)
FastVisionModel.for_inference(model) 

def create_prompt(idea, template):
    user_content = f"""Role: You are an ai meme idea classifier to identify whether a meme idea is generated by ai or human.
    Task: Given the meme idea and template, classify whether it's an ai generated idea or human idea.
    
    Meme:
    - meme idea: "{idea}"
    - meme template: "{template}"
    
    Instruction: 
    Is this an ai generated meme idea?
    
    Output Format:
    On the very last line, output "label: AI" or "label: Human\""""

    messages = [
        {"role": "user", "content": [{"type": "text", "text": user_content}]}
    ]
    return processor.apply_chat_template(messages, add_generation_prompt=True)

def evaluate_dataset(csv_file, batch_size=8):
    print(f"evaluating: {csv_file}")
    df = pd.read_csv(csv_file)
    
    df['template'] = df['template'].fillna('N/A')
    
    y_true = df['label'].tolist()
    y_pred = [] 
    
    for i in tqdm(range(0, len(df), batch_size), desc="Inferencing"):
        batch_df = df.iloc[i:i+batch_size]
        
        prompts = [create_prompt(row['idea_text'], row['template']) for _, row in batch_df.iterrows()]
        
        processor.tokenizer.padding_side = "left" 
        inputs = processor(
            text = prompts,
            images = None, 
            padding = True,
            return_tensors = "pt"
        ).to("cuda")
        
        input_length = inputs["input_ids"].shape[1]
        
        with torch.no_grad():
            outputs = model.generate(
                **inputs, 
                max_new_tokens=10, 
                use_cache=True,
                do_sample=True,    
                temperature=0.7      
            )
            
        new_tokens = outputs[:, input_length:]
        
        decoded_responses = processor.batch_decode(new_tokens, skip_special_tokens=True)
        
        for text in decoded_responses:
            text_lower = text.lower().strip()
            if "label: ai" in text_lower:
                y_pred.append(1)
            elif "label: human" in text_lower:
                y_pred.append(0)
            else:
                if "ai" in text_lower and "human" not in text_lower:
                    y_pred.append(1)
                elif "human" in text_lower and "ai" not in text_lower:
                    y_pred.append(0)
                else:
                    print(f"\n[Warning] output format wrong, default label: Human(0). output: '{text}'")
                    y_pred.append(0)
                    
    acc = accuracy_score(y_true, y_pred)
    prec = precision_score(y_true, y_pred, zero_division=0)
    rec = recall_score(y_true, y_pred, zero_division=0)
    f1 = f1_score(y_true, y_pred, zero_division=0)
    
    print(f"--> [Seed {seed} Result] Accuracy: {acc:.4f} | Precision: {prec:.4f} | Recall: {rec:.4f} | F1: {f1:.4f}")
    
    return acc, prec, rec, f1

seeds = [0, 1, 2, 3, 4]
datasets_to_eval = ["dev_set.csv", "test_set.csv"]
all_results = {ds: {"acc": [], "prec": [], "rec": [], "f1": []} for ds in datasets_to_eval}

BATCH_SIZE = 4 

for seed in seeds:
    print(f"\n" + "="*40)
    print(f"        RUNNING WITH SEED: {seed}")
    print("="*40)
    
    set_seed(seed)
    
    for ds in datasets_to_eval:
        acc, prec, rec, f1 = evaluate_dataset(ds, batch_size=BATCH_SIZE)
        
        all_results[ds]["acc"].append(acc)
        all_results[ds]["prec"].append(prec)
        all_results[ds]["rec"].append(rec)
        all_results[ds]["f1"].append(f1)
print("\n\n" + "#"*40)
print("      FINAL RESULTS ACROSS 3 SEEDS")
print("#"*40)

for ds in datasets_to_eval:
    print(f"\ndataset: {ds}")
    print("-" * 30)
    n = len(all_results[ds]["acc"]) 
    sqrt_n = np.sqrt(n)
    
    avg_acc = np.mean(all_results[ds]["acc"])
    se_acc = np.std(all_results[ds]["acc"], ddof=1) / sqrt_n
    
    avg_prec = np.mean(all_results[ds]["prec"])
    se_prec = np.std(all_results[ds]["prec"], ddof=1) / sqrt_n
    
    avg_rec = np.mean(all_results[ds]["rec"])
    se_rec = np.std(all_results[ds]["rec"], ddof=1) / sqrt_n
    
    avg_f1 = np.mean(all_results[ds]["f1"])
    se_f1 = np.std(all_results[ds]["f1"], ddof=1) / sqrt_n
    
    print(f"Accuracy : {avg_acc:.4f} ± {se_acc:.4f}")
    print(f"Precision: {avg_prec:.4f} ± {se_prec:.4f}")
    print(f"Recall   : {avg_rec:.4f} ± {se_rec:.4f}")
    print(f"F1 Score : {avg_f1:.4f} ± {se_f1:.4f}")