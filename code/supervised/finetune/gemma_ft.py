from unsloth import FastVisionModel
import torch
from datasets import load_dataset

model, processor = FastVisionModel.from_pretrained(
    "google/gemma-4-31B-it",   
    load_in_4bit = True, 
    device_map = "balanced",
    use_gradient_checkpointing = "unsloth",
)
model = FastVisionModel.get_peft_model(
    model,
    finetune_vision_layers     = False, 
    finetune_language_layers   = True, 
    finetune_attention_modules = True, 
    finetune_mlp_modules       = True, 
    r = 32,
    lora_alpha = 32,
    lora_dropout = 0,
    bias = "none",
    random_state = 3407,
    use_rslora = False,  
    loftq_config = None, 
    target_modules = "all-linear",
)

dataset = load_dataset("csv", data_files={"train": "train_set.csv", "dev": "dev_set.csv"})
train_dataset = dataset["train"]

def convert_to_conversation(sample):
    output_label = "label: AI" if sample['label'] == 1 else "label: Human"
    
    user_content = f"""Role: You are an ai meme idea classifier to identify whether a meme idea is generated by ai or human.
    Task: Given the meme idea and template, classify whether it's an ai generated idea or human idea.
    
    Meme:
    - meme idea: "{sample['idea_text']}"
    - meme template: "{sample['template']}"
    
    Instruction: 
    Is this an ai generated meme idea?
    
    Output Format:
    On the very last line, output "label: AI" or "label: Human\""""

    conversation = [
        {
            "role": "user",
            "content": [{"type": "text", "text": user_content}],
        },
        {
            "role": "assistant", 
            "content": [{"type": "text", "text": output_label}],
        },
    ]
    return {"messages": conversation}
    
converted_dataset = train_dataset.map(convert_to_conversation)

from unsloth import get_chat_template
processor = get_chat_template(
    processor,
    "gemma-4"
)

from unsloth.trainer import UnslothVisionDataCollator
from trl import SFTTrainer, SFTConfig
from unsloth import is_bfloat16_supported

trainer = SFTTrainer(
    model = model,
    train_dataset = converted_dataset,
    processing_class = processor.tokenizer,
    data_collator = UnslothVisionDataCollator(model, processor),
    args = SFTConfig(
        per_device_train_batch_size = 8,
        gradient_accumulation_steps = 4,
        warmup_steps = 5,
        max_steps = 60,
        learning_rate = 2e-4,
        fp16 = not is_bfloat16_supported(),
        bf16 = is_bfloat16_supported(),
        logging_steps = 1,
        optim = "adamw_8bit",
        weight_decay = 0.001,
        lr_scheduler_type = "cosine",
        seed = 3407,
        output_dir = "outputs",
        report_to = "none", 
        
        remove_unused_columns = False,
        dataset_text_field = "",
        dataset_kwargs = {"skip_prepare_dataset": True},
        max_seq_length = 2048,
    ),
)

trainer_stats = trainer.train()

FastVisionModel.for_inference(model)

sample_dev = dataset["dev"][0]

test_content = f"""Role: You are an ai meme idea classifier to identify whether a meme idea is generated by ai or human.
    Task: Given the meme idea and template, classify whether it's an ai generated idea or human idea.
    
    Meme:
    - meme idea: "{sample_dev['idea_text']}"
    - meme template: "{sample_dev['template']}"
    
    Instruction: 
    Is this an ai generated meme idea?
    
    Output Format:
    On the very last line, output "label: AI" or "label: Human\""""

messages = [
    {
        "role": "user",
        "content": [{"type": "text", "text": test_content}]
    }
]

input_text = processor.apply_chat_template(messages, add_generation_prompt = True)

inputs = processor(
    text = input_text,
    images = None, 
    add_special_tokens = False,
    return_tensors = "pt",
).to("cuda")

from transformers import TextStreamer
text_streamer = TextStreamer(processor.tokenizer, skip_prompt = True)
_ = model.generate(**inputs, streamer = text_streamer, max_new_tokens = 10, use_cache = True)

model.save_pretrained("gemma_4_meme") 
processor.save_pretrained("gemma_4_meme")